@dataclasses.dataclass
class ScenarioOutcome:
    """Hemodynamic before-and-after comparison result."""
    scenario: SimulationScenario
    baseline_params: WindkesselParameters
    perturbed_params: WindkesselParameters
    baseline_metrics: BeatMetrics
    perturbed_metrics: BeatMetrics
    # Uncertainty intervals for perturbed outcome [5th, 95th]
    sbp_ci: Tuple[float, float]
    dbp_ci: Tuple[float, float]
    hr_ci: Tuple[float, float]
    map_ci: Tuple[float, float]
    delta_sbp: float
    delta_dbp: float
    delta_map: float
    delta_pp: float
    delta_hr: float
    disclaimer: str = "Illustrative simulation based on mathematical model. Not a clinical medical prediction."


def simulate_whatif(
    current_estimate: TwinEstimate,
    scenario_key: str = "exercise",
    custom_deltas: Optional[Dict[str, float]] = None,
    Rc_fixed: float = 0.038,
    n_mc_samples: int = 50,
) -> ScenarioOutcome:
    """Run what-if scenario perturbation on the current digital twin state.

    Args:
        current_estimate: Current TwinEstimate containing state and posterior covariance
        scenario_key: One of 'exercise', 'stress', 'high_sodium', 'vasodilator', 'stiffening', 'custom'
        custom_deltas: Optional dict with 'delta_rp_pct', 'delta_c_pct', 'delta_sv_pct', 'delta_hr_pct'
        Rc_fixed: Aortic impedance resistance
        n_mc_samples: Number of Monte Carlo draws for propagating posterior uncertainty

    Returns:
        ScenarioOutcome with metrics, waveforms, and uncertainty bands
    """
    scenario = PRESET_SCENARIOS.get(scenario_key, PRESET_SCENARIOS["exercise"])

    # Determine percentage multipliers
    if scenario_key == "custom" and custom_deltas is not None:
        d_rp = float(custom_deltas.get("delta_rp_pct", 0.0))
        d_c = float(custom_deltas.get("delta_c_pct", 0.0))
        d_sv = float(custom_deltas.get("delta_sv_pct", 0.0))
        d_hr = float(custom_deltas.get("delta_hr_pct", 0.0))
    else:
        d_rp = scenario.delta_rp_pct
        d_c = scenario.delta_c_pct
        d_sv = scenario.delta_sv_pct
        d_hr = scenario.delta_hr_pct

    base_p = WindkesselParameters(
        Rp=current_estimate.Rp,
        C=current_estimate.C,
        Rc=Rc_fixed,
        SV=current_estimate.SV,
        HR=current_estimate.HR,
    )

    # Compute perturbed parameters
    new_rp = float(np.clip(base_p.Rp * (1.0 + d_rp / 100.0), 0.35, 2.80))
    new_c = float(np.clip(base_p.C * (1.0 + d_c / 100.0), 0.25, 3.20))
    new_sv = float(np.clip(base_p.SV * (1.0 + d_sv / 100.0), 25.0, 160.0))
    new_hr = float(np.clip(base_p.HR * (1.0 + d_hr / 100.0), 38.0, 195.0))

    pert_p = WindkesselParameters(
        Rp=new_rp,
        C=new_c,
        Rc=Rc_fixed,
        SV=new_sv,
        HR=new_hr,
    )

    # Full continuous pressure waveforms solved via solve_ivp
    base_metrics = simulate_windkessel_ivp(base_p, n_cycles=4, points_per_cycle=120)
    pert_metrics = simulate_windkessel_ivp(pert_p, n_cycles=4, points_per_cycle=120)

    # Monte Carlo uncertainty propagation from posterior state covariance
    cov = current_estimate.state_cov
    mean = current_estimate.state_mean
    rng = np.random.default_rng(42)

    cov_clean = 0.5 * (cov + cov.T) + 1e-6 * np.eye(4)
    try:
        raw_samples = rng.multivariate_normal(mean, cov_clean, size=n_mc_samples)
    except Exception:
        stds = np.sqrt(np.maximum(1e-6, np.diag(cov_clean)))
        raw_samples = mean[None, :] + rng.normal(0, 1, size=(n_mc_samples, 4)) * stds[None, :]

    # Apply the same scenario delta percentage to each sampled posterior vector
    pert_samples = np.zeros_like(raw_samples)
    pert_samples[:, 0] = np.clip(raw_samples[:, 0] * (1.0 + d_rp / 100.0), 0.30, 2.80)
    pert_samples[:, 1] = np.clip(raw_samples[:, 1] * (1.0 + d_c / 100.0), 0.25, 3.20)
    pert_samples[:, 2] = np.clip(raw_samples[:, 2] * (1.0 + d_sv / 100.0), 25.0, 160.0)
    pert_samples[:, 3] = np.clip(raw_samples[:, 3] * (1.0 + d_hr / 100.0), 38.0, 195.0)

    sim_sbp = np.zeros(n_mc_samples)
    sim_dbp = np.zeros(n_mc_samples)
    sim_hr = np.zeros(n_mc_samples)
    sim_map = np.zeros(n_mc_samples)

    for i in range(n_mc_samples):
        h, s, d = fast_windkessel_beat(
            Rp=pert_samples[i, 0],
            C=pert_samples[i, 1],
            Rc=Rc_fixed,
            SV=pert_samples[i, 2],
            HR=pert_samples[i, 3],
        )
        sim_hr[i] = h
        sim_sbp[i] = s
        sim_dbp[i] = d
        sim_map[i] = (2.0 * d + s) / 3.0

    sbp_ci = (float(np.percentile(sim_sbp, 5)), float(np.percentile(sim_sbp, 95)))
    dbp_ci = (float(np.percentile(sim_dbp, 5)), float(np.percentile(sim_dbp, 95)))
    hr_ci = (float(np.percentile(sim_hr, 5)), float(np.percentile(sim_hr, 95)))
    map_ci = (float(np.percentile(sim_map, 5)), float(np.percentile(sim_map, 95)))

    delta_sbp = pert_metrics.sbp - base_metrics.sbp
    delta_dbp = pert_metrics.dbp - base_metrics.dbp
    delta_map = pert_metrics.map_ - base_metrics.map_
    delta_pp = pert_metrics.pulse_pressure - base_metrics.pulse_pressure
    delta_hr = pert_metrics.hr - base_metrics.hr

    return ScenarioOutcome(
        scenario=scenario,
        baseline_params=base_p,
        perturbed_params=pert_p,
        baseline_metrics=base_metrics,
        perturbed_metrics=pert_metrics,
        sbp_ci=sbp_ci,
        dbp_ci=dbp_ci,
        hr_ci=hr_ci,
        map_ci=map_ci,
        delta_sbp=round(delta_sbp, 1),
        delta_dbp=round(delta_dbp, 1),
        delta_map=round(delta_map, 1),
        delta_pp=round(delta_pp, 1),
        delta_hr=round(delta_hr, 1),
    )
