"""What-If Simulation Engine for CardioTwin X.

Evaluates acute and chronic hemodynamic perturbations applied to the patient's
current digital twin state:
- Scenarios: Moderate Exercise, Acute Stress, High Sodium Diet, Vasodilator Therapy,
  Arterial Stiffening, and Custom Multi-Parameter Sliders.
- Propagates posterior parameter covariance to generate predictive uncertainty bands.
- Produces full cardiac cycle aortic pressure waveforms before and after perturbation.

DISCLAIMER: All simulations generated by this module are illustrative mathematical
models of cardiovascular mechanics. They are NOT clinical predictions or medical advice.
"""

