"""Synthetic Patient Data Generator for CardioTwin X.

Generates physiologically realistic 24-hour hemodynamic time series at 1-minute
resolution (1,440 steps) with circadian rhythms, physiological stressors
(exercise, mental stress), realistic measurement noise, and injected anomalies
(acute vasoconstriction, paroxysmal tachycardia, and sensor dropouts).

DISCLAIMER: All data generated by this module is purely synthetic mathematical
simulation for research and demonstration purposes. Not real patient data.
"""

from __future__ import annotations

import dataclasses
from typing import Any, Dict, List, Optional, Tuple
import numpy as np
