from .model import WindkesselParameters, fast_windkessel_beat


@dataclasses.dataclass
class PatientProfile:
    """Historical clinical profile and baseline parameter definition."""
    patient_id: str
    name: str
    age: int
    gender: str
    bmi: float
    smoker: bool
    baseline_bp: str
    condition: str
    base_params: WindkesselParameters
    description: str
    is_synthetic: bool = True

    def to_dict(self) -> Dict[str, Any]:
        """Convert clinical profile to dictionary."""
        return {
            "patient_id": self.patient_id,
            "name": self.name,
            "age": self.age,
            "gender": self.gender,
            "bmi": self.bmi,
            "smoker": self.smoker,
            "baseline_bp": self.baseline_bp,
            "condition": self.condition,
            "description": self.description,
            "is_synthetic": True,
            "base_Rp": self.base_params.Rp,
            "base_C": self.base_params.C,
            "base_Rc": self.base_params.Rc,
            "base_SV": self.base_params.SV,
            "base_HR": self.base_params.HR,
        }


