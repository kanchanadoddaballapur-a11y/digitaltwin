def generate_synthetic_patient_timeseries(
    preset_key: str = "healthy",
    duration_hours: int = 24,
    resolution_min: int = 1,
    random_seed: int = 42,
    inject_anomalies: bool = True,
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """Generate 24-hour synthetic cardiovascular time series at 1-minute resolution.

    Features:
    - Circadian rhythm (dipping during sleep 01:00 - 06:00, morning surge at 07:00 - 09:00).
    - Physiological stressors:
        * Acute mental stress episode at ~14:00 (minutes 810 to 835)
        * Aerobic exercise session at ~17:15 (minutes 1035 to 1070)
    - Sensor noise (realistic Gaussian noise).
    - 3 Injected anomalies (if enabled):
        1. Acute peripheral vasoconstriction / resistance surge (min 1190 to 1235)
        2. Paroxysmal tachycardia episode (min 460 to 485)
        3. Sensor dropout / missing telemetry (min 670 to 690)
    - 3 ECG-derived markers:
        * RR interval (ms)
        * HRV-SDNN (ms, beat-to-beat variability)
        * QT interval (ms, Bazett-derived)

    Args:
        preset_key: 'healthy', 'hypertensive', or 'elderly'.
        duration_hours: Total duration in hours (default 24h).
        resolution_min: Time step in minutes (default 1 min).
        random_seed: Reproducibility seed.
        inject_anomalies: Whether to embed clinical anomalies and missing telemetry.

    Returns:
        (DataFrame, history_dict)
    """
    rng = np.random.default_rng(random_seed)
    profile = get_patient_profile(preset_key)
    base_p = profile.base_params

    total_steps = int((duration_hours * 60) / resolution_min)
    time_min = np.arange(total_steps) * resolution_min

    # True physiological parameters at each time point
    true_Rp = np.full(total_steps, base_p.Rp, dtype=np.float64)
    true_C = np.full(total_steps, base_p.C, dtype=np.float64)
    true_SV = np.full(total_steps, base_p.SV, dtype=np.float64)
    true_HR = np.full(total_steps, base_p.HR, dtype=np.float64)
    true_Rc = np.full(total_steps, base_p.Rc, dtype=np.float64)

    # 1. Circadian variation: 24h period = 1440 min
    # Peak in afternoon (~16:00, t=960 min), nadir in deep sleep (~03:30, t=210 min)
    circadian_phase = 2.0 * np.pi * (time_min - 960) / 1440.0
    circadian_factor = np.cos(circadian_phase)  # +1 in afternoon, -1 in night

    # Physiological circadian modulation:
    # Sleep: HR drops ~12%, Rp drops ~6%, SV stays stable
    true_HR += 0.09 * base_p.HR * circadian_factor
    true_Rp += 0.05 * base_p.Rp * circadian_factor

    # 2. Stress Episode at t = 810 to 835 (25 min, ~13:30 - 13:55)
    # Sympathetic surge: HR increases +25%, Rp increases +20%, SV slight increase +5%
    stress_idx = (time_min >= 810) & (time_min <= 835)
    stress_t = (time_min[stress_idx] - 810) / 25.0
    stress_envelope = np.sin(np.pi * stress_t) ** 2
    true_HR[stress_idx] += 22.0 * stress_envelope
    true_Rp[stress_idx] += (0.22 * base_p.Rp) * stress_envelope
    true_SV[stress_idx] += 4.0 * stress_envelope

    # 3. Moderate Exercise Episode at t = 1035 to 1070 (35 min, ~17:15 - 17:50)
    # Exercise hemodynamics: HR up to 135 bpm (+55-65 bpm), SV up (+25 ml),
    # Peripheral resistance drops by -35% due to active skeletal muscle vasodilation
    ex_idx = (time_min >= 1035) & (time_min <= 1070)
    ex_t = (time_min[ex_idx] - 1035) / 35.0
    ex_envelope = np.sin(np.pi * ex_t) ** 1.5
    true_HR[ex_idx] += 58.0 * ex_envelope
    true_SV[ex_idx] += 24.0 * ex_envelope
    true_Rp[ex_idx] -= (0.38 * base_p.Rp) * ex_envelope

    # 4. Injected Anomalies (if enabled)
    anomaly_labels = np.full(total_steps, "Normal", dtype=object)

    if inject_anomalies:
        # Anomaly A: Paroxysmal Tachycardia (min 460 - 485, ~07:40 morning)
        # Abrupt cardiac rate surge to ~145 bpm without vascular metabolic adaptation
        tachy_idx = (time_min >= 460) & (time_min <= 485)
        tachy_envelope = np.ones(np.sum(tachy_idx))
        # ramp up and down
        n_tachy = len(tachy_envelope)
        ramp = np.minimum(np.arange(n_tachy) / 4.0, (n_tachy - 1 - np.arange(n_tachy)) / 4.0)
        tachy_envelope = np.clip(ramp, 0.0, 1.0)
        true_HR[tachy_idx] += 70.0 * tachy_envelope
        true_SV[tachy_idx] -= 14.0 * tachy_envelope  # reduced diastolic filling time
        anomaly_labels[tachy_idx] = "Paroxysmal Tachycardia"

        # Anomaly B: Sensor Dropout / Telemetry loss (min 670 - 690, ~11:10)
        dropout_idx = (time_min >= 670) & (time_min <= 690)
        anomaly_labels[dropout_idx] = "Sensor Dropout"

        # Anomaly C: Sudden SVR/Resistance Surge (min 1190 - 1235, ~19:50 evening)
        # Acute vasoconstriction / hypertensive spike (Rp jumps +45%, compliance drops -20%)
        surge_idx = (time_min >= 1190) & (time_min <= 1235)
        surge_t = (time_min[surge_idx] - 1190) / 45.0
        surge_envelope = np.sin(np.pi * surge_t) ** 1.2
        true_Rp[surge_idx] += (0.50 * base_p.Rp) * surge_envelope
        true_C[surge_idx] -= (0.22 * base_p.C) * surge_envelope
        anomaly_labels[surge_idx] = "Acute Vascular Resistance Surge"

    # Add small physiological baseline random walk drift
    drift = np.cumsum(rng.normal(0.0, 0.002, total_steps))
    true_Rp = np.clip(true_Rp + drift * 0.05, 0.35, 2.8)
    true_C = np.clip(true_C, 0.3, 3.2)
    true_SV = np.clip(true_SV, 30.0, 150.0)
    true_HR = np.clip(true_HR, 40.0, 190.0)

    # Calculate exact hemodynamic response via analytical Windkessel forward model
    sbp_clean = np.zeros(total_steps, dtype=np.float64)
    dbp_clean = np.zeros(total_steps, dtype=np.float64)

    for i in range(total_steps):
        _, sbp_val, dbp_val = fast_windkessel_beat(
            Rp=true_Rp[i],
            C=true_C[i],
            Rc=true_Rc[i],
            SV=true_SV[i],
            HR=true_HR[i],
        )
        sbp_clean[i] = sbp_val
        dbp_clean[i] = dbp_val

    # Add measurement noise
    hr_obs = true_HR + rng.normal(0.0, 1.2, total_steps)
    sbp_obs = sbp_clean + rng.normal(0.0, 2.2, total_steps)
    dbp_obs = dbp_clean + rng.normal(0.0, 1.8, total_steps)

    # Ensure physiological ordering (SBP > DBP + 15)
    sbp_obs = np.maximum(sbp_obs, dbp_obs + 16.0)

    # 3 ECG-Derived Features
    # 1. RR Interval in ms = 60000 / HR + beat variability
    rr_intervals = (60000.0 / np.maximum(35.0, hr_obs)) + rng.normal(0.0, 12.0, total_steps)

    # 2. HRV-SDNN in ms: High at rest/sleep (~55-75 ms), decreases during stress/exercise (~18-28 ms)
    base_sdnn = 55.0 if preset_key == "healthy" else (40.0 if preset_key == "hypertensive" else 30.0)
    hrv_sdnn = base_sdnn * (75.0 / np.maximum(45.0, hr_obs)) + rng.normal(0.0, 3.5, total_steps)
    hrv_sdnn = np.clip(hrv_sdnn, 12.0, 110.0)

    # 3. QT-like interval in ms: Bazett formula QT = QTc * sqrt(RR/1000)
    # Typical QTc ~ 410 ms for males, 425 ms for females
    qtc = 415.0 if profile.gender == "Male" else 425.0
    rr_sec = np.maximum(0.3, rr_intervals / 1000.0)
    qt_intervals = qtc * np.sqrt(rr_sec) + rng.normal(0.0, 5.0, total_steps)

    # Apply sensor dropouts if anomalies are enabled
    if inject_anomalies:
        dropout_mask = anomaly_labels == "Sensor Dropout"
        hr_obs[dropout_mask] = np.nan
        sbp_obs[dropout_mask] = np.nan
        dbp_obs[dropout_mask] = np.nan
        rr_intervals[dropout_mask] = np.nan
        hrv_sdnn[dropout_mask] = np.nan
        qt_intervals[dropout_mask] = np.nan

    # Create timestamp strings (simulating a 24-hour cycle starting at 00:00)
    hour = (time_min // 60) % 24
    minute = time_min % 60
    timestamps = [f"{h:02d}:{m:02d}" for h, m in zip(hour, minute)]

    df = pd.DataFrame({
        "time_min": time_min,
        "timestamp": timestamps,
        "hr_obs": np.round(hr_obs, 1),
        "sbp_obs": np.round(sbp_obs, 1),
        "dbp_obs": np.round(dbp_obs, 1),
        "rr_interval_ms": np.round(rr_intervals, 1),
        "hrv_sdnn_ms": np.round(hrv_sdnn, 1),
        "qt_interval_ms": np.round(qt_intervals, 1),
        "true_Rp": np.round(true_Rp, 3),
        "true_C": np.round(true_C, 3),
        "true_SV": np.round(true_SV, 1),
        "true_HR": np.round(true_HR, 1),
        "anomaly_event": anomaly_labels,
        "is_synthetic": True,
    })

    metadata = {
        "is_synthetic": True,
        "dataset_name": f"CardioTwin-X-{preset_key.capitalize()}-24h",
        "total_records": len(df),
        "patient_profile": profile.to_dict(),
        "sampling_rate": "1 minute",
        "disclaimer": "Synthetic simulation. Not clinical patient data.",
    }

    return df, metadata
